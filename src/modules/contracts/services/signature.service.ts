import { and, eq } from "drizzle-orm";
import { db } from "@/core/db";
import { AppError } from "@/core/errors";
import { publish } from "@/core/events";
import { createLogger } from "@/core/logger";
import { sendEmail } from "@/core/aws";
import { contracts, contractSignatures } from "../schema";
import type { SignatureRequestInput } from "../domain/validation";

const log = createLogger("contracts.signatures");

/**
 * Request signatures on a contract.
 *
 * Provider-agnostic on purpose: rows are created here and an email goes out,
 * while `externalEnvelopeId` is the seam where a DocuSign/Adobe envelope id is
 * recorded once that integration is wired. The contract's lifecycle state does
 * not depend on which provider is used.
 */
export async function requestSignatures(input: SignatureRequestInput) {
  const contract = await db.query.contracts.findFirst({ where: eq(contracts.id, input.contractId) });
  if (!contract) throw AppError.notFound("Contract");

  if (contract.missingClauses.length > 0) {
    throw AppError.policy(
      "Contract is missing mandatory clauses and cannot be sent for signature",
      { missingClauses: contract.missingClauses }
    );
  }

  const rows = await db
    .insert(contractSignatures)
    .values(
      input.signers.map((s) => ({
        contractId: input.contractId,
        signerName: s.name,
        signerEmail: s.email,
        isCounterparty: s.isCounterparty,
        status: "SENT" as const,
        sentAt: new Date(),
      }))
    )
    .returning();

  await db
    .update(contracts)
    .set({ status: "PENDING_SIGNATURE" })
    .where(eq(contracts.id, input.contractId));

  for (const signer of input.signers) {
    await sendEmail({
      to: signer.email,
      subject: `[SAINT] Signature requested — ${contract.title} (${contract.contractNumber})`,
      body: [
        `${signer.name},`,
        ``,
        `Your signature is requested on ${contract.title} (${contract.contractNumber}).`,
        contract.totalValue ? `Contract value: ${contract.currency} ${contract.totalValue}` : "",
        contract.expiryDate ? `Expires: ${contract.expiryDate.toISOString().slice(0, 10)}` : "",
        ``,
        `This request was generated by SAINT.`,
      ].join("\n"),
    });
  }

  log.info("signatures requested", { contractId: input.contractId, signers: rows.length });
  return rows;
}

/** Record one signatory's decision; the contract activates once all have signed. */
export async function recordSignature(
  signatureId: string,
  outcome: "SIGNED" | "DECLINED",
  envelopeId?: string
) {
  const [signature] = await db
    .update(contractSignatures)
    .set({
      status: outcome,
      signedAt: outcome === "SIGNED" ? new Date() : null,
      externalEnvelopeId: envelopeId,
    })
    .where(eq(contractSignatures.id, signatureId))
    .returning();
  if (!signature) throw AppError.notFound("Signature request");

  if (outcome === "DECLINED") {
    await db.update(contracts).set({ status: "IN_REVIEW" }).where(eq(contracts.id, signature.contractId));
    return signature;
  }

  const outstanding = await db
    .select({ id: contractSignatures.id })
    .from(contractSignatures)
    .where(
      and(
        eq(contractSignatures.contractId, signature.contractId),
        eq(contractSignatures.status, "SENT")
      )
    );

  if (outstanding.length === 0) {
    const [contract] = await db
      .update(contracts)
      .set({ status: "ACTIVE" })
      .where(eq(contracts.id, signature.contractId))
      .returning();
    await publish("contract.signed", {
      contractId: contract.id,
      supplierId: contract.supplierId,
    });
    log.info("contract fully executed", { contractId: contract.id });
  }

  return signature;
}
